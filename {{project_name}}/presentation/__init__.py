"""Слой presentation — входящие адаптеры: HTTP, CLI, консьюмеры.

Импорты: application (IInteractor, DTO, порты) и фреймворки (FastAPI,
pydantic). Из domain — только исключения, чтобы перевести их в ответ.
Нельзя: сущности и объекты-значения domain; конкретные классы
infrastructure — их подставляет composition.

Сюда относится:
- Свои схемы запроса и ответа. DTO интерактора и сущности наружу
  не отдаются.
- Маппинг: схема запроса → DTO интерактора, DTO → схема ответа.
- Вызов интерактора, полученного через DI как IInteractor[In, Out].
- Транспортные детали: коды ответа, заголовки, валидация формата.
- Реализация порта IIdentityProvider: читает токен или сессию из
  запроса и возвращает идентификатор пользователя примитивом (UUID, str)
  или None. Сущность пользователя не создаёт и не загружает, в БД
  не ходит, domain не импортирует.
- Реализации портов лежат в подпакете своего entrypoint
  (presentation/fastapi, presentation/cli) и попадают только в контейнер
  этого entrypoint: он регистрирует их через PortProvider(<подпакет>).
  Реализации в корне presentation не регистрируются.

Сюда не относится:
- Бизнес-правила и ветвления по предметной логике → domain или
  application.
- Загрузка сущности пользователя, ролей пользователя и проверка прав →
  интерактор в application.
- Запросы к БД и внешним API → infrastructure, через порт.
- Создание приложения и контейнера, запуск сервера → composition.
"""
